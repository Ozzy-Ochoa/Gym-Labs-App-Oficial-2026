// Cálculo científico de calorias gastas por exercício e sessão (Compêndio ACSM)
export function calculateActivityCalories(
  met: number = 5.0,
  userWeightKg: number = 75,
  durationMinutes: number = 10,
  completedSets: number = 0,
  totalVolumeKg: number = 0
): number {
  const safeWeight = userWeightKg > 30 ? userWeightKg : 75;
  const safeDuration = Math.max(1, durationMinutes);
  // Fórmula ACSM: Kcal = (MET * 3.5 * pesoKg / 200) * minutos
  const baseKcal = ((met * 3.5 * safeWeight) / 200) * safeDuration;
  // Bônus mecânico por séries concluídas e tonelagem levantada
  const setBonus = completedSets * 4.5;
  const volumeBonus = (totalVolumeKg / 1000) * 1.5;
  return Math.max(1, Math.round(baseKcal + setBonus + volumeBonus));
}

